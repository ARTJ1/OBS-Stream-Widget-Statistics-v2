  let lang = 'ru';

  function t(key, vars) {
    const table = DICT[lang] || DICT.ru;
    let s = table[key] ?? DICT.ru[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  }

  function getLang() {
    return lang;
  }

  function applyI18n(next) {
    if (next === 'en' || next === 'ru') lang = next;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (!key) return;
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(key));
    });
    const sel = document.getElementById('uiLangSelect');
    if (sel) sel.value = lang;
    window.dispatchEvent(new CustomEvent('admin-i18n', { detail: { lang } }));
  }

  function skinDesc(skin) {
    if (!skin) return '';
    if (lang === 'en') return SKIN_DESC_EN[skin.id] || skin.desc || skin.name;
    return skin.desc || skin.name;
  }

  window.AdminI18n = { t, getLang, applyI18n, setLang: applyI18n, skinDesc, DICT };
